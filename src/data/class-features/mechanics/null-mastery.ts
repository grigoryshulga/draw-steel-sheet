import type { FeatureCondition, FeatureMechanics } from "../types";

/**
 * Мастерство дисциплины Нуля: 18 строк таблиц трёх традиций и три базовые
 * записи традиций.
 *
 * Строка таблицы активируется только своей традицией и порогом дисциплины:
 * `when.keyValue` отсекает чужую традицию из списка, `when.resourceAtLeast`
 * показывается на листе бейджем «нужно N дисциплины». Условие продублировано
 * в эффекте и в триггере: список активных записей порог ресурса не скрывает,
 * поэтому без условия на эффекте число применялось бы при любой дисциплине.
 *
 * Общий `stackingGroup` у бонусов к принудительному перемещению (строка 12 и
 * порог 2 Метакинетика): одинаковый бонус, равный Интуиции, не складывается
 * сам с собой.
 */
function masteryWhen(tradition: string, value: number): FeatureCondition {
  return {
    keyValue: [tradition],
    resourceAtLeast: { name: "Дисциплина", value },
  };
}

