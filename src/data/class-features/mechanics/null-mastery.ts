/** Прибавка временной выносливости на 12 дисциплины: общая для трёх таблиц. */
function heroicTemporaryStamina(condition: FeatureCondition) {
  return {
    event: "use-ability" as const,
    frequency: "always" as const,
    label: "Используешь героическую способность",
    detail:
      "Всякий раз, когда вы используете героическую способность, вы " +
      "получаете 10 очков временной выносливости.",
    when: condition,
  };
}

